-- RLS decides which ROWS a signed-in user may touch. Nothing decided which
-- COLUMNS. Every table in public grants table-wide UPDATE to `authenticated`
-- through Supabase's platform default privileges, so a member who may
-- legitimately update a row could also rewrite that row's identity and
-- provenance — its id, its workspace, who created it, and when.
--
-- WHAT THIS IS WORTH, stated accurately: integrity and defence in depth, not
-- closing a live escalation. Every policy that gates ACCESS on created_by also
-- requires created_by = (select auth.uid()) in its USING, so a member can only
-- rewrite rows they already own; rewriting workspace_id is bounded by the WITH
-- CHECK requiring membership of the destination. What changes is that the
-- database stops permitting a class of write the application never makes, so a
-- future policy written slightly too loosely cannot be compounded by column
-- rewriting.
--
-- THE ASSUMPTION THIS RESTS ON, measured rather than reasoned: most of these
-- tables have a BEFORE UPDATE trigger assigning NEW.updated_at. If column
-- privileges applied to that assignment, this migration would break every
-- update in the application. They do not — probed on the live database with
-- update(updated_at) revoked on public.notes, where an authenticated session
-- still updated a row successfully.
--
-- Generated by a loop rather than ~156 hand-written column names. A
-- transcription error across that many is close to certain; a loop cannot make
-- one.
--
-- DEVIATION FROM THE ORIGINAL DRAFT, found by running it: `revoke
-- update(col) on table from authenticated` only removes a COLUMN-level ACL
-- entry (pg_attribute.attacl). Every table here except public.signals grants
-- authenticated UPDATE at the TABLE level instead (pg_class.relacl shows
-- `authenticated=arwdDxtm`, Supabase's platform default) — has_table_privilege
-- confirms it. A table-wide grant already lets you update every column, so
-- revoking a column-specific slice that was never separately held is exactly
-- the silent no-op this migration's own comment warns about: the assertion
-- below caught it on the first push, reporting essentially every protected
-- column on every table still writable. public.signals was the one table
-- where the naive revoke worked, because 202608180001 had already stripped
-- its table-wide UPDATE and re-granted only update(read_at) at the column
-- level — it was never table-wide to begin with.
--
-- The fix follows that same proven pattern for every other table: revoke the
-- table-wide UPDATE outright, then grant column-level UPDATE back for every
-- column except the five identity/provenance ones. This still touches only
-- UPDATE — INSERT, SELECT, DELETE are untouched — and only tables where
-- authenticated actually holds table-wide UPDATE and actually has one of the
-- protected columns, so public.signals is correctly left alone.

do $$
declare
  target record;
  allowed_cols text;
begin
  for target in
    select pc.oid, pc.relname as table_name
    from pg_class pc
    join pg_namespace n on n.oid = pc.relnamespace and n.nspname = 'public'
    where pc.relkind = 'r'
      and has_table_privilege('authenticated', pc.oid, 'UPDATE')
      and exists (
        select 1
        from information_schema.columns c
        where c.table_schema = 'public'
          and c.table_name = pc.relname
          and c.column_name in ('id', 'workspace_id', 'created_by', 'created_at', 'updated_at')
      )
    order by pc.relname
  loop
    -- Strip the table-wide grant. This removes UPDATE on every column,
    -- protected or not — the next step adds the non-protected ones back.
    execute format('revoke update on public.%I from authenticated', target.table_name);

    select string_agg(quote_ident(c.column_name), ', ' order by c.ordinal_position)
    into allowed_cols
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.table_name = target.table_name
      and c.column_name not in ('id', 'workspace_id', 'created_by', 'created_at', 'updated_at');

    if allowed_cols is not null then
      execute format('grant update (%s) on public.%I to authenticated', allowed_cols, target.table_name);
    end if;
  end loop;
end
$$;

-- Assert in BOTH directions. A revoke that overreached and a revoke that did
-- nothing both leave a green migration behind, and they are opposite failures.
do $$
declare
  still_writable text;
begin
  select string_agg(c.table_name || '.' || c.column_name, ', ' order by c.table_name, c.column_name)
  into still_writable
  from information_schema.columns c
  join pg_class pc on pc.relname = c.table_name
  join pg_namespace n on n.oid = pc.relnamespace and n.nspname = 'public'
  where c.table_schema = 'public'
    and pc.relkind = 'r'
    and c.column_name in ('id', 'workspace_id', 'created_by', 'created_at', 'updated_at')
    and has_column_privilege('authenticated', ('public.' || quote_ident(c.table_name))::regclass, c.column_name, 'UPDATE');

  if still_writable is not null then
    raise exception 'authenticated can still update: %', still_writable;
  end if;

  -- The canary. If the revoke overreached, ordinary editing is broken and this
  -- fails the push rather than the app failing later for every user.
  if not has_column_privilege('authenticated', 'public.notes', 'title', 'UPDATE') then
    raise exception 'the revoke overreached: authenticated can no longer update notes.title';
  end if;

  -- Inserts create rows BY setting these columns. If INSERT were caught too,
  -- nothing could be created at all.
  if not has_column_privilege('authenticated', 'public.notes', 'workspace_id', 'INSERT') then
    raise exception 'the revoke caught INSERT as well as UPDATE; nothing can be created';
  end if;
end
$$;
