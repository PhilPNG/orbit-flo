-- 202608200001 revoked every anon grant in public and asserted, as its second
-- check, that `authenticated` can still SELECT all 34 public base tables that
-- existed that day. That assertion has been silently wrong since the tables
-- below were created: nine tables in this schema never received an explicit
-- `grant ... to authenticated` from any migration. They work today only
-- because Supabase's platform default privileges (owned by `supabase_admin`,
-- the same mechanism documented in 202608200001) grant ALL on every new
-- public table to anon, authenticated and service_role at creation time. On
-- the hosted project that happened silently and nobody noticed.
--
-- Applied to a clean database, there is no platform layer standing behind a
-- freshly-run migration set — `supabase db reset` runs these files and
-- nothing else. Measured on a real local stack: `supabase db reset` aborts
-- outright, because 202608200001's own self-check fires with "authenticated
-- can now read only 25 of 34 public tables; the revoke overreached". The
-- revoke didn't overreach; it correctly revoked from anon and never had
-- anything to do with these nine, which is exactly the bug — the schema was
-- never reproducible from its own migrations, it just happened to work on a
-- database that was never actually rebuilt from them.
--
-- The nine: board_columns, labels, project_rituals, recurrence_rules,
-- template_usage, work_item_attachments, work_item_checklist_items,
-- work_item_comments, work_item_labels. Found by diffing every `create table
-- public.<x>` in supabase/migrations/ against every `grant ... to
-- authenticated` — exactly the check re-run below in this migration's own
-- report to the operator, and the one to re-run after this file lands.
--
-- WHAT THIS GRANTS, and why it deliberately mirrors platform defaults rather
-- than something narrower: the goal is a database that ends up in the same
-- state whether it was created by Supabase's platform (hosted, defaults
-- applied) or by replaying every migration on an empty database (local,
-- nothing but this repo). So table-wide SELECT, INSERT, DELETE — matching
-- what the platform already silently grants on hosted — making this migration
-- a no-op there and a repair everywhere else.
--
-- UPDATE is different on purpose. 202608200006 already established, for every
-- other table, that table-wide UPDATE lets a member rewrite a row's identity
-- and provenance (id, workspace_id, created_by, created_at, updated_at) even
-- though RLS bounds which rows they may touch at all. These nine tables were
-- never given table-wide UPDATE by any migration in this repo either — only
-- by the same platform default — so granting it table-wide here and relying
-- on 202608200006 to narrow it later would leave a window (and 202608200006
-- has already run; it cannot see tables created after it). Instead this file
-- grants column-level UPDATE directly, skipping the five protected columns,
-- landing these nine in the exact same end state 202608200006 left every
-- other table in. anon and service_role are untouched, for the same reasons
-- 202608200001 and 202608200006 left them untouched: anon must hold nothing,
-- and the service_role gap is a separate, deliberately out-of-scope problem.
--
-- Column list generated by a loop against information_schema.columns, not
-- transcribed by hand, following 202608200006's structure exactly — the same
-- reasoning applies: a hand-typed list across nine tables and roughly sixty
-- columns is close to certain to contain a transcription error, and a loop
-- cannot make one.

-- Table-wide grants, written literally rather than looped: nine statements
-- naming nine tables, matching the style every other table-wide grant in this
-- repo already uses (see 202606280001). If one of these table names were
-- wrong, an unqualified `grant ... on public.<typo>` fails the migration
-- outright rather than silently granting nothing, which is the same safety
-- a loop over information_schema would have bought here for no benefit.
grant select, insert, delete on public.board_columns to authenticated;
grant select, insert, delete on public.labels to authenticated;
grant select, insert, delete on public.project_rituals to authenticated;
grant select, insert, delete on public.recurrence_rules to authenticated;
grant select, insert, delete on public.template_usage to authenticated;
grant select, insert, delete on public.work_item_attachments to authenticated;
grant select, insert, delete on public.work_item_checklist_items to authenticated;
grant select, insert, delete on public.work_item_comments to authenticated;
grant select, insert, delete on public.work_item_labels to authenticated;

-- Column-level UPDATE grants, looped rather than transcribed: roughly sixty
-- columns across nine tables, the same order of magnitude 202608200006 called
-- out as "close to certain" to contain a transcription error by hand.
do $$
declare
  target_table text;
  allowed_cols text;
begin
  foreach target_table in array array[
    'board_columns',
    'labels',
    'project_rituals',
    'recurrence_rules',
    'template_usage',
    'work_item_attachments',
    'work_item_checklist_items',
    'work_item_comments',
    'work_item_labels'
  ]
  loop
    select string_agg(quote_ident(c.column_name), ', ' order by c.ordinal_position)
    into allowed_cols
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.table_name = target_table
      and c.column_name not in ('id', 'workspace_id', 'created_by', 'created_at', 'updated_at');

    if allowed_cols is not null then
      execute format('grant update (%s) on public.%I to authenticated', allowed_cols, target_table);
    end if;
  end loop;
end
$$;

-- Assert in both directions, same discipline as 202608200001 and
-- 202608200006: a grant that didn't reach far enough and a grant that reached
-- too far both leave a green migration behind on their own, and they are
-- opposite failures.
do $$
declare
  unreadable text;
  overreached text;
begin
  -- Direction one: re-run 202608200001's own check. Every public base table —
  -- ordinary and partitioned, 'r' and 'p' — must now be SELECT-able by
  -- authenticated. This is the exact condition that migration asserts and
  -- that a clean `supabase db reset` was failing on before this file existed.
  select string_agg(pc.relname, ', ' order by pc.relname)
  into unreadable
  from pg_class pc
  join pg_namespace n on n.oid = pc.relnamespace and n.nspname = 'public'
  where pc.relkind in ('r', 'p')
    and not has_table_privilege('authenticated', pc.oid, 'SELECT');

  if unreadable is not null then
    raise exception 'authenticated still cannot SELECT: %', unreadable;
  end if;

  -- Direction two: the column loop above must not have granted UPDATE on any
  -- of the five protected columns on any of the nine tables it touched. Scoped
  -- to just these nine — other tables are 202608200006's responsibility and
  -- already have their own assertion.
  select string_agg(c.table_name || '.' || c.column_name, ', ' order by c.table_name, c.column_name)
  into overreached
  from information_schema.columns c
  where c.table_schema = 'public'
    and c.table_name in (
      'board_columns',
      'labels',
      'project_rituals',
      'recurrence_rules',
      'template_usage',
      'work_item_attachments',
      'work_item_checklist_items',
      'work_item_comments',
      'work_item_labels'
    )
    and c.column_name in ('id', 'workspace_id', 'created_by', 'created_at', 'updated_at')
    and has_column_privilege('authenticated', ('public.' || quote_ident(c.table_name))::regclass, c.column_name, 'UPDATE');

  if overreached is not null then
    raise exception 'authenticated can update protected columns that should be locked: %', overreached;
  end if;
end
$$;
